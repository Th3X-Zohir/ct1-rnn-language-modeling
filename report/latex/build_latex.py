"""Generate LaTeX macros and tables for the paper from the result files.

Writes report/latex/generated/{macros.tex, tab_*.tex}. Every number in paper.tex comes from
these files, so the paper always matches the experiments.
Usage:  python report/latex/build_latex.py
"""
import csv
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parent / "generated"
OUT.mkdir(exist_ok=True)


def rcsv(name):
    return list(csv.DictReader(open(ROOT / "results" / "tables" / f"{name}.csv", encoding="utf-8")))


def rjson(rel):
    return json.loads((ROOT / rel).read_text())


def f3(x):
    return f"{float(x):.3f}"


runs = {r["Run"]: r for r in rcsv("all_runs")}
ng = rjson("results/ngram_baseline.json")
ngd = {g["order"]: g for g in ng}
best_ng = min(ng, key=lambda g: g["test_bpc"])
summ = rjson("results/summary.json")
fin = rjson("results/final/E6_gru_long.json")
samp = rjson("results/sampling.json")
S = {r["strategy"]: r for r in samp["rows"]}
ref = samp["reference_test_text"]
it = rjson("results/interpretability.json")
U = {u["property"]: u for u in it["units"]}
PR = {p["property"]: p for p in it["probes"]}
corpus = rcsv("corpus_statistics")
tot = corpus[-1]
meta = rjson("data/processed/meta.json")
spars = {int(r["n"]): float(r["unseen_val_ngrams_pct"]) for r in rcsv("ngram_sparsity")}
params = {r["Cell"]: r for r in rcsv("model_params")}

MACRO_NAME = {"E1_rnn": "rnn", "E1_gru": "gru", "E1_lstm": "lstm", "E2_lstm_seq32": "seqA", "E2_lstm_seq64": "seqB",
              "E2_lstm_seq256": "seqD", "E3_lstm_h128": "hsmall", "E3_lstm_h384": "hlarge", "E3_lstm_L1": "lone",
              "E3_lstm_L3": "lthree"}          # seqC = seq 128 = E1_lstm
M = {}
for k, r in runs.items():
    key = MACRO_NAME[k]
    M[f"tbpc{key}"] = f3(r["Test BPC"]); M[f"vbpc{key}"] = f3(r["Val BPC"])
    M[f"ppl{key}"] = f3(r["Test PPL"]); M[f"min{key}"] = r["Train time (min)"]; M[f"par{key}"] = r["Params (M)"]
for o, g in ngd.items():
    w = {3: "three", 5: "five", 7: "seven"}[o]
    M[f"ng{w}"] = f3(g["test_bpc"]); M[f"ngval{w}"] = f3(g["val_bpc"]); M[f"ngppl{w}"] = f3(g["test_ppl"])
M["ngctxfive"] = f"{ngd[5]['n_contexts'] / 1e3:.0f}"
M["unigramH"] = f3(summ["unigram_entropy"]); M["unigramPPL"] = f"{2 ** summ['unigram_entropy']:.2f}"
M["bestbpc"] = f3(fin["test_bpc"]); M["bestppl"] = f3(fin["test_ppl"]); M["bestval"] = f3(fin["best_val_bpc"])
M["finsteps"] = f"{fin['config']['steps']:,}".replace(",", "{,}"); M["finmin"] = f"{fin['train_time_s'] / 60:.0f}"
M["finratio"] = f"{fin['config']['steps'] / 2500:.1f}"; M["finepochs"] = f"{fin['config']['steps'] * 8192 / 3.6427e6:.1f}"
M["fingain"] = f3(float(runs["E1_gru"]["Test BPC"]) - fin["test_bpc"])
M["finvsng"] = f"{100 * (best_ng['test_bpc'] - fin['test_bpc']) / best_ng['test_bpc']:.1f}"
M["gruvsng"] = f"{100 * (best_ng['test_bpc'] - float(runs['E1_gru']['Test BPC'])) / best_ng['test_bpc']:.1f}"
M["totchars"] = f"{int(tot['Clean chars']) / 1e6:.2f}"; M["rawchars"] = f"{int(tot['Raw chars']) / 1e6:.2f}"
M["totwords"] = f"{int(tot['Words']) / 1e3:.0f}"; M["vocab"] = str(meta["vocab_size"])
M["trainchars"] = f"{meta['split_chars']['train']:,}".replace(",", "{,}")
M["valchars"] = f"{meta['split_chars']['val']:,}".replace(",", "{,}")
M["testchars"] = f"{meta['split_chars']['test']:,}".replace(",", "{,}")
for n, w in ((5, "five"), (7, "seven"), (8, "eight"), (10, "ten")):
    M[f"unseen{w}"] = f"{spars[n]:.1f}"
for c in ("RNN", "GRU", "LSTM"):
    M[f"params{c}"] = f"{int(params[c]['Total']):,}".replace(",", "{,}")
q, qp = U["inside quotation"], PR["inside quotation"]
b, w = U["next char starts a word"], PR["position inside word"]
M["qunit"] = str(q["best unit"]); M["qr"] = f"{abs(q['pearson r']):.2f}"
M["qacc"] = f"{100 * qp['hidden state']:.1f}"; M["qacccur"] = f"{100 * qp['current char only']:.1f}"
M["qmaj"] = f"{100 * qp['majority baseline']:.1f}"
M["bunit"] = str(b["best unit"]); M["br"] = f"{abs(b['pearson r']):.2f}"
M["wordrtwo"] = f"{w['hidden state']:.2f}"; M["wordrtwocur"] = f"{w['current char only']:.2f}"
M["interpchars"] = f"{it['n_chars']:,}".replace(",", "{,}")
M["greedyrep"] = f"{100 * S['greedy']['repeat_4gram_rate']:.0f}"; M["greedydtwo"] = f3(S["greedy"]["distinct_2"])
M["greedynll"] = f3(S["greedy"]["self_nll_bpc"])
M["nucvalid"] = f"{100 * S['nucleus_0.9']['valid_word_rate']:.1f}"; M["nucdtwo"] = f3(S["nucleus_0.9"]["distinct_2"])
M["tfivevalid"] = f"{100 * S['temp_0.5']['valid_word_rate']:.1f}"; M["tonevalid"] = f"{100 * S['temp_1.0']['valid_word_rate']:.1f}"
M["thirteenvalid"] = f"{100 * S['temp_1.3']['valid_word_rate']:.1f}"; M["refvalid"] = f"{100 * ref['valid_word_rate']:.1f}"
M["tfivedone"] = f3(S["temp_0.5"]["distinct_1"]); M["tonedone"] = f3(S["temp_1.0"]["distinct_1"])

with open(OUT / "macros.tex", "w", encoding="utf-8") as fh:
    fh.write("% generated by build_latex.py -- do not edit\n")
    for k, v in sorted(M.items()):
        fh.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")


def table(name, cols, header, rows, wide=False, size="\\footnotesize"):
    lines = [size, f"\\begin{{tabular}}{{{cols}}}", "\\toprule", " & ".join(header) + " \\\\", "\\midrule"]
    lines += [" & ".join(str(c) for c in r) + " \\\\" for r in rows]
    lines += ["\\bottomrule", "\\end{tabular}"]
    (OUT / f"{name}.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


table("tab_corpus", "lrrrr", ["Novel", "Raw chars", "Clean chars", "Words", "Types"],
      [[r["Book"].replace("TOTAL", "\\textbf{Total}"), f"{int(r['Raw chars']):,}", f"{int(r['Clean chars']):,}",
        f"{int(r['Words']):,}", f"{int(r['Unique words']):,}"] for r in corpus])

table("tab_params", "lrrrr", ["Cell", "Embedding", "Recurrent", "Output", "Total"],
      [[c, f"{int(params[c]['Embedding']):,}", f"{int(params[c]['Recurrent']):,}", f"{int(params[c]['Output']):,}",
        f"{int(params[c]['Total']):,}"] for c in ("RNN", "GRU", "LSTM")])

order = ["E1_rnn", "E1_gru", "E1_lstm", "E2_lstm_seq32", "E2_lstm_seq64", "E2_lstm_seq256",
         "E3_lstm_h128", "E3_lstm_h384", "E3_lstm_L1", "E3_lstm_L3"]
best_ctrl = min(order, key=lambda k: float(runs[k]["Val BPC"]))
rows = []
for k in order:
    r = runs[k]; bold = (lambda s: f"\\textbf{{{s}}}") if k == best_ctrl else (lambda s: s)
    rows.append([k.split("_")[0], r["Cell"], r["Hidden"], r["Layers"], r["Seq len"], r["Params (M)"],
                 bold(f3(r["Val BPC"])), bold(f3(r["Test BPC"])), f3(r["Test PPL"]), r["Train time (min)"]])
table("tab_runs", "llrrrrrrrr", ["Exp.", "Cell", "$H$", "$L$", "$T$", "Params (M)", "Val BPC", "Test BPC", "Test PPL", "Time (min)"], rows)

base_rows = [["Unigram (no context)", "--", f3(summ["unigram_entropy"]), f"{2 ** summ['unigram_entropy']:.2f}"]]
base_rows += [[f"Witten--Bell {g['order']}-gram", f3(g["val_bpc"]), f3(g["test_bpc"]), f3(g["test_ppl"])] for g in ng]
for k, lab in (("E1_rnn", "Vanilla RNN $256\\times2$"), ("E1_lstm", "LSTM $256\\times2$"), ("E1_gru", "GRU $256\\times2$")):
    base_rows.append([lab, f3(runs[k]["Val BPC"]), f3(runs[k]["Test BPC"]), f3(runs[k]["Test PPL"])])
base_rows.append(["\\textbf{GRU $256\\times2$, long (E6)}", f"\\textbf{{{f3(fin['best_val_bpc'])}}}",
                  f"\\textbf{{{f3(fin['test_bpc'])}}}", f"\\textbf{{{f3(fin['test_ppl'])}}}"])
table("tab_baselines", "lrrr", ["Model", "Val BPC", "Test BPC", "Test PPL"], base_rows)

names = {"greedy": "Greedy", "temp_0.5": "$\\tau=0.5$", "temp_0.8": "$\\tau=0.8$", "temp_1.0": "$\\tau=1.0$",
         "temp_1.3": "$\\tau=1.3$", "top_k_5": "Top-$k$ ($k=5$)", "nucleus_0.9": "Nucleus ($p=0.9$)"}
srows = [[names[r["strategy"]], f3(r["valid_word_rate"]), f3(r["distinct_1"]), f3(r["distinct_2"]),
          f3(r["repeat_4gram_rate"]), f3(r["self_nll_bpc"])] for r in samp["rows"]]
srows.append(["\\textit{Real text (test)}", f3(ref["valid_word_rate"]), f3(ref["distinct_1"]), f3(ref["distinct_2"]),
              f3(ref["repeat_4gram_rate"]), "--"])
table("tab_sampling", "lrrrrr", ["Strategy", "Valid", "Dist-1", "Dist-2", "Rep-4", "NLL"], srows)

prow = []
for p in it["probes"]:
    metric = "Acc." if p["type"] == "accuracy" else "$R^2$"
    prow.append([p["property"].replace("(log)", "(log)"), metric, f3(p["hidden state"]), f3(p["current char only"]),
                 f3(p["majority baseline"]) if p["type"] == "accuracy" else "0", f"{U[p['property']]['best unit']} ({U[p['property']]['pearson r']:+.2f})"])
table("tab_probes", "llrrrl", ["Property", "Metric", "Hidden", "Char", "Base", "Best unit ($r$)"], prow)
print(f"wrote {len(M)} macros and 6 tables to {OUT}")
